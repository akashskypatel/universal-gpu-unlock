#!/usr/bin/env python3
"""Build and run the host simulator for the active transaction sources.

    python3 tools/run_simulation.py prepare
    python3 tools/run_simulation.py transaction

The simulator compiles the same sources the firmware builders compile, with
GU_SIMULATED_ACTUATION, and links them against a modelled UEFI environment and
a modelled AD102 PCI function. Nothing here is hardware evidence: the report
is tagged SIM_ and the build profile cannot be used to produce an EFI image.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIM = ROOT / "sim"
BUILD = SIM / "build"
INCLUDE = BUILD / "include"

APP_SOURCES = [
    "app.c", "driver_nvram.c", "boot_io.c", "msi_release.c", "unlock_execution.c",
    "port.c", "compat.c", "checks.c", "gpu_inventory.c", "gpu_discovery.c",
    "gpu_execution_state.c", "gpu_windows_path.c", "profile.c", "gpu_selection.c", "gpu_sku_geometry.c", "boot_state.c", "sha256.c",
    "runtime.c", "format.c", "vendor/unlock_610.c", "vendor/prep_610.c",
    "vendor/layout_610.c", "vendor/vbios_610.c", "vendor/gfw_eval.c",
]
SIM_SOURCES = ["sim_world.c", "sim_gpu.c", "sim_main.c"]

DEFINES = [
    "-DGU_SIMULATED_ACTUATION",
    "-DGU_AD104_TRANSACTION",
    "-DGU_ENTRY_LATCHED_SS1_FULL",
    "-DGU_ACTIVE_SINGLE_TARGET",
    # The simulator exercises the shipping selection path: the image is built
    # with no compiled target list and reads the operator variable instead.
    "-DGU_RUNTIME_SELECTION",
]

INCLUDES = [
    "-I", str(ROOT / "src"),
    "-I", str(ROOT / "src" / "compat"),
    "-I", str(ROOT / "src" / "vendor"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include" / "X64"),
    "-I", str(SIM),
    "-I", str(INCLUDE),
]

# Extra flags for diagnosis (for example "-fsanitize=address").
EXTRA = os.environ.get("SIM_CFLAGS", "").split()

BASE = ["-std=c11", "-fshort-wchar", "-O1", "-g", "-Wall", "-Wextra",
        "-Wno-unused-parameter", *EXTRA, *DEFINES, *INCLUDES]
# The image sources are compiled in the kernel-style environment they expect;
# the simulator's own files need a hosted libc instead.
APP_FLAGS = [*BASE, "-D__KERNEL__"]
# The simulator must not see src/compat/linux/*: those headers shadow the host
# <linux/*> headers. It talks to the image only through the public headers.
SIM_INCLUDES = [
    "-I", str(ROOT / "src"),
    "-I", str(ROOT / "src" / "vendor"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include" / "X64"),
    "-I", str(SIM),
    "-I", str(INCLUDE),
]
SIM_FLAGS = ["-std=c11", "-fshort-wchar", "-O1", "-g", "-Wall", "-Wextra",
             "-Wno-unused-parameter", "-D_GNU_SOURCE", *EXTRA, *DEFINES,
             *SIM_INCLUDES]

BOOT_PROFILE = """/* Generated by tools/run_simulation.py. Simulator-only partition GUID. */
#pragma once
#define GU_WINDOWS_PARTITION_INITIALIZER \\
  {0x7c9e4f10,0x1b2d,0x4c3a,{0x9e,0x55,0x21,0x0a,0x44,0x8b,0x6d,0xf1}}
"""


def compiler() -> str:
    for candidate in ("gcc", "clang"):
        path = shutil.which(candidate)
        if path:
            return path
    raise SystemExit("no host C compiler found")


def prepare_tree() -> None:
    INCLUDE.mkdir(parents=True, exist_ok=True)
    (INCLUDE / "local").mkdir(exist_ok=True)
    (INCLUDE / "local" / "boot_profile.h").write_text(BOOT_PROFILE, encoding="utf-8")
    stale = INCLUDE / "gpu-selection.h"
    if stale.exists():
        stale.unlink()          # the image no longer compiles in a target list

    esp = BUILD / "esp"
    esp.mkdir(exist_ok=True)
    for arch in ("AD102-ASSETS", "GA102-ASSETS"):
        target = esp / arch
        source = ROOT / arch
        if not source.is_dir():
            continue
        if target.is_symlink() or target.exists():
            if target.is_symlink():
                target.unlink()
            elif target.is_dir():
                shutil.rmtree(target)
        target.symlink_to(source, target_is_directory=True)

    windows = BUILD / "windows"
    boot = windows / "EFI" / "Microsoft" / "Boot"
    boot.mkdir(parents=True, exist_ok=True)
    (boot / "bootmgfw.efi").write_bytes(b"MZ simulator stand-in for the Windows boot manager\n")


def build() -> Path:
    cc = compiler()
    objects = []
    for source in APP_SOURCES:
        obj = BUILD / (Path(source).stem + ".o")
        command = [cc, *APP_FLAGS, "-c", str(ROOT / "src" / source), "-o", str(obj)]
        done = subprocess.run(command, capture_output=True, text=True)
        if done.returncode != 0:
            sys.stderr.write(done.stderr)
            raise SystemExit("compile failed: %s" % source)
        objects.append(obj)
    for source in SIM_SOURCES:
        obj = BUILD / ("sim_" + Path(source).stem + ".o")
        command = [cc, *SIM_FLAGS, "-c", str(SIM / source), "-o", str(obj)]
        done = subprocess.run(command, capture_output=True, text=True)
        if done.returncode != 0:
            sys.stderr.write(done.stderr)
            raise SystemExit("compile failed: %s" % source)
        objects.append(obj)
    binary = BUILD / "sim_active"
    command = [cc, *EXTRA, *[str(o) for o in objects], "-o", str(binary)]
    done = subprocess.run(command, capture_output=True, text=True)
    if done.returncode != 0:
        sys.stderr.write(done.stderr)
        raise SystemExit("link failed")
    return binary


VARIANTS = ("nominal", "msi-enabled", "flr-refused", "dma-high", "rebar",
            "bar-above-4g", "runtime-target", "runtime-absent", "ad104-sku")

# Scenario matrix: every row must pass, and the two negative rows are the
# documented refusal and abort paths.
SCENARIOS = (
    ("prepare", "nominal"),
    ("transaction", "nominal"),
    ("prepare", "msi-enabled"),
    ("transaction", "flr-refused"),
    ("transaction", "dma-high"),
    ("transaction", "rebar"),
    ("transaction", "bar-above-4g"),
    # Target selection resolved from the operator variable, not from the build.
    ("prepare", "runtime-target"),
    ("prepare", "runtime-absent"),
    # An Ada SKU admitted by the id list but with no captured register table.
    ("prepare", "ad104-sku"),
)


def run(binary: Path, stage: str, variant: str) -> subprocess.CompletedProcess:
    command = [str(binary), stage, str(BUILD / "esp"),
               str(BUILD / "windows"), variant]
    return subprocess.run(command, capture_output=True, text=True)


def main() -> int:
    stage = sys.argv[1] if len(sys.argv) > 1 else "prepare"
    if stage == "verify":
        prepare_tree()
        binary = build()
        results = []
        for scenario_stage, variant in SCENARIOS:
            done = run(binary, scenario_stage, variant)
            summary = ""
            for line in done.stdout.splitlines():
                if line.startswith("SIM_RESULT=") and "CHECKS_FAILED" in line:
                    summary = line.strip()
            results.append((scenario_stage, variant, done.returncode, summary))
            print("%-12s %-12s rc=%d  %s" % (scenario_stage, variant,
                                             done.returncode, summary))
        failed = [r for r in results if r[2] != 0]
        print("SIM_VERIFY=%s SCENARIOS=%d FAILED=%d"
              % ("PASS" if not failed else "FAIL", len(results), len(failed)))
        return 1 if failed else 0
    if stage not in ("prepare", "transaction"):
        raise SystemExit("unknown stage: %s (use prepare, transaction or verify)"
                         % stage)
    variant = sys.argv[2] if len(sys.argv) > 2 else "nominal"
    if variant not in VARIANTS:
        raise SystemExit("unknown variant: %s" % variant)
    prepare_tree()
    binary = build()
    done = run(binary, stage, variant)
    sys.stdout.write(done.stdout)
    if done.stderr.strip():
        sys.stdout.write("\n--- stderr ---\n" + done.stderr)
    return done.returncode


if __name__ == "__main__":
    raise SystemExit(main())
