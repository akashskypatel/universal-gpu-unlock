#!/usr/bin/env python3
"""Build and run the host simulator for the active transaction sources.

    python3 tools/run_simulation.py prepare
    python3 tools/run_simulation.py transaction

The simulator compiles the same sources the firmware builders compile, with
GU_SIMULATED_ACTUATION, and links them against a modelled UEFI environment and
a modelled AD102 PCI function. Nothing here is hardware evidence: the report
is tagged SIM_ and the build profile cannot be used to produce an EFI image.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIM = ROOT / "sim"
BUILD = SIM / "build"
INCLUDE = BUILD / "include"

APP_SOURCES = [
    "app.c", "driver_nvram.c", "boot_io.c", "msi_release.c", "stop_contract.c",
    "launch_source.c",
    "unlock_execution.c",
    "port.c", "compat.c", "checks.c", "gpu_inventory.c", "gpu_discovery.c",
    "gpu_execution_state.c", "gpu_windows_path.c", "profile.c", "prom_reference.c", "gpu_selection.c", "gpu_sku_geometry.c", "boot_state.c", "asset_install.c", "sha256.c",
    "runtime.c", "format.c", "vendor/unlock_610.c", "vendor/prep_610.c",
    "vendor/layout_610.c", "vendor/vbios_610.c", "vendor/gfw_eval.c",
]
SIM_SOURCES = ["sim_world.c", "sim_gpu.c", "sim_main.c"]

DEFINES = [
    "-DGU_SIMULATED_ACTUATION",
    "-DGU_AD104_TRANSACTION",
    "-DGU_ENTRY_LATCHED_SS1_FULL",
    "-DGU_ACTIVE_SINGLE_TARGET",
    # The simulator exercises the shipping selection path: the image is built
    # with no compiled target list and reads the operator variable instead.
    "-DGU_RUNTIME_SELECTION",
]

INCLUDES = [
    "-I", str(ROOT / "src"),
    "-I", str(ROOT / "src" / "compat"),
    "-I", str(ROOT / "src" / "vendor"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include" / "X64"),
    "-I", str(SIM),
    "-I", str(INCLUDE),
]

# Extra flags for diagnosis (for example "-fsanitize=address").
EXTRA = os.environ.get("SIM_CFLAGS", "").split()

BASE = ["-std=c11", "-fshort-wchar", "-O1", "-g", "-Wall", "-Wextra",
        "-Wno-unused-parameter", *EXTRA, *DEFINES, *INCLUDES]
# Flags without the image's include paths: the simulator's own files must not
# see src/compat/linux, which shadows the host headers it expects.
BASE_ONLY = ["-std=c11", "-fshort-wchar", "-O1", "-g", "-Wall", "-Wextra",
             "-Wno-unused-parameter", *EXTRA]
# The image sources are compiled in the kernel-style environment they expect;
# the simulator's own files need a hosted libc instead.
APP_FLAGS = [*BASE, "-D__KERNEL__"]
# The simulator must not see src/compat/linux/*: those headers shadow the host
# <linux/*> headers. It talks to the image only through the public headers.
SIM_INCLUDES = [
    "-I", str(ROOT / "src"),
    "-I", str(ROOT / "src" / "vendor"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include"),
    "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include" / "X64"),
    "-I", str(SIM),
    "-I", str(INCLUDE),
]
SIM_FLAGS = ["-std=c11", "-fshort-wchar", "-O1", "-g", "-Wall", "-Wextra",
             "-Wno-unused-parameter", "-D_GNU_SOURCE", *EXTRA, *DEFINES,
             *SIM_INCLUDES]

BOOT_PROFILE = """/* Generated by tools/run_simulation.py. Simulator-only partition GUID. */
#pragma once
#define GU_WINDOWS_PARTITION_INITIALIZER \\
  {0x7c9e4f10,0x1b2d,0x4c3a,{0x9e,0x55,0x21,0x0a,0x44,0x8b,0x6d,0xf1}}
"""


def compiler() -> str:
    for candidate in ("gcc", "clang"):
        path = shutil.which(candidate)
        if path:
            return path
    raise SystemExit("no host C compiler found")


def prepare_tree() -> None:
    INCLUDE.mkdir(parents=True, exist_ok=True)
    (INCLUDE / "local").mkdir(exist_ok=True)
    (INCLUDE / "local" / "boot_profile.h").write_text(BOOT_PROFILE, encoding="utf-8")
    stale = INCLUDE / "gpu-selection.h"
    if stale.exists():
        stale.unlink()          # the image no longer compiles in a target list

    esp = BUILD / "esp"
    esp.mkdir(exist_ok=True)
    for arch in ("AD102-ASSETS", "GA102-ASSETS"):
        target = esp / arch
        source = ROOT / arch
        if not source.is_dir():
            continue
        if target.is_symlink() or target.exists():
            if target.is_symlink():
                target.unlink()
            elif target.is_dir():
                shutil.rmtree(target)
        target.symlink_to(source, target_is_directory=True)

    windows = BUILD / "windows"
    # Start every run with an empty ESP: the install scenario must prove the
    # staging path, not inherit a previous run's files.
    staged = windows / "AD102-ASSETS"
    if staged.is_dir() and not staged.is_symlink():
        shutil.rmtree(staged)
    boot = windows / "EFI" / "Microsoft" / "Boot"
    boot.mkdir(parents=True, exist_ok=True)
    (boot / "bootmgfw.efi").write_bytes(b"MZ simulator stand-in for the Windows boot manager\n")


# The stock profile is a build-time choice. The default binary is built with the
# entry-latched policy (no fixed selector expectation); the second one is built
# for the captured original-03100062 value, so the profile gate can be exercised
# end to end rather than only on the host predicate.
STOCK_BUILDS = {
    "default": [],
    "original": ["-DGU_STOCK_PROFILE_ORIGINAL_03100062"],
    "observed": ["-DGU_STOCK_PROFILE_OBSERVED_03000062"],
    "preserve": ["-DGU_ENTRY_LATCHED_SS1_PRESERVE"],
    # A bounded firmware timer, well above any plausible runtime for the
    # sequence: the point is that a hang reboots instead of freezing.
    "bounded": ["-DGU_WATCHDOG_SECONDS=600"],
    # Per-card acceptance: nothing captured, so nothing admitted.
    "prom": ["-DGU_PROM_REFERENCE_REQUIRED"],
    # The same gate with the model's own digest pinned, so the admitted path is
    # exercised too. Test-only by construction (see prom_reference.c).
    "prom-synthetic": ["-DGU_PROM_REFERENCE_REQUIRED",
                       "-DGU_PROM_REFERENCE_SYNTHETIC"],
}
# The default profile is replaced, not added to: exactly one profile is allowed.
# Exactly one stock profile is allowed, so a row that names a policy replaces the
# default one instead of adding to it. Rows that only change something else (the
# watchdog bound) keep the default policy.
REPLACED_BY_DEFAULT_PROFILE = ["-DGU_ENTRY_LATCHED_SS1_FULL"]
POLICY_PROFILES = ("original", "observed", "preserve")


def build(profile: str = "default") -> Path:
    cc = compiler()
    defines = [flag for flag in DEFINES]
    if profile in POLICY_PROFILES:
        defines = [flag for flag in defines if flag not in REPLACED_BY_DEFAULT_PROFILE]
    defines += STOCK_BUILDS[profile]
    suffix = "" if profile == "default" else "_" + profile
    objects = []
    for source in APP_SOURCES:
        obj = BUILD / (Path(source).stem + suffix + ".o")
        command = [cc, *BASE_ONLY, *defines, "-D__KERNEL__", *INCLUDES,
                   "-c", str(ROOT / "src" / source), "-o", str(obj)]
        done = subprocess.run(command, capture_output=True, text=True)
        if done.returncode != 0:
            sys.stderr.write(done.stderr)
            raise SystemExit("compile failed: %s" % source)
        objects.append(obj)
    for source in SIM_SOURCES:
        obj = BUILD / ("sim_" + Path(source).stem + suffix + ".o")
        # The simulator's own files are hosted: no kernel-style environment.
        command = [cc, *BASE_ONLY, *defines, "-D_GNU_SOURCE", *SIM_INCLUDES,
                   "-c", str(SIM / source), "-o", str(obj)]
        done = subprocess.run(command, capture_output=True, text=True)
        if done.returncode != 0:
            sys.stderr.write(done.stderr)
            raise SystemExit("compile failed: %s" % source)
        objects.append(obj)
    binary = BUILD / ("sim_active" + suffix)
    command = [cc, *EXTRA, *[str(o) for o in objects], "-o", str(binary)]
    done = subprocess.run(command, capture_output=True, text=True)
    if done.returncode != 0:
        sys.stderr.write(done.stderr)
        raise SystemExit("link failed")
    return binary


VARIANTS = ("nominal", "msi-enabled", "flr-refused", "dma-high", "rebar",
            "bar-above-4g", "runtime-target", "runtime-absent", "ad104-sku",
            "install-assets", "stock-match", "stock-mismatch", "watchdog",
            "preserve", "untracked", "prom-refused", "prom-admitted")

# Scenario matrix: every row must pass, and the two negative rows are the
# documented refusal and abort paths.
SCENARIOS = (
    ("prepare", "nominal"),
    ("transaction", "nominal"),
    ("prepare", "msi-enabled"),
    ("transaction", "flr-refused"),
    ("transaction", "dma-high"),
    ("transaction", "rebar"),
    ("transaction", "bar-above-4g"),
    # Target selection resolved from the operator variable, not from the build.
    ("prepare", "runtime-target"),
    ("prepare", "runtime-absent"),
    # An Ada SKU admitted by the id list but with no captured register table.
    ("prepare", "ad104-sku"),
    # The staging build: USB bundle verified, copied to the ESP, recorded.
    ("prepare", "install-assets"),
    # The original-03100062 build: accepted on the card it was built for,
    # refused on the other captured stock value. Both rows run the same
    # binary, so the difference is the card, not the image.
    ("prepare", "stock-match", "original"),
    ("prepare", "stock-mismatch", "original"),
    # The bounded build: the timer is armed with the configured threshold, the
    # transaction still completes, and the cancel removes it before handover.
    ("transaction", "watchdog", "bounded"),
    # One row per selector contract, so each policy is exercised and not merely
    # compiled: preserve writes SS0 only, the non-latched build writes both.
    ("transaction", "preserve", "preserve"),
    ("transaction", "untracked", "original"),
    # Per-card firmware acceptance: with no captured reference the card is
    # refused before any write, and with the model's reference pinned it is
    # admitted - the two rows differ only in what the build knows.
    ("prepare", "prom-refused", "prom"),
    ("prepare", "prom-admitted", "prom-synthetic"),
)


# A single-run invocation has to pick the same binary the verify row uses,
# otherwise `transaction preserve` silently runs the default image.
VARIANT_PROFILE = {row[1]: (row[2] if len(row) > 2 else "default")
                   for row in SCENARIOS}


def run(binary: Path, stage: str, variant: str) -> subprocess.CompletedProcess:
    command = [str(binary), stage, str(BUILD / "esp"),
               str(BUILD / "windows"), variant]
    return subprocess.run(command, capture_output=True, text=True)


def main() -> int:
    stage = sys.argv[1] if len(sys.argv) > 1 else "prepare"
    if stage == "matrix":
        prepare_tree()
        for name in STOCK_BUILDS:
            build(name)
            print(f"SIM_MATRIX_PROFILE={name} BUILD=PASS")
        print(f"SIM_MATRIX=PASS PROFILES={len(STOCK_BUILDS)}")
        return 0

    if stage == "verify":
        prepare_tree()
        binaries = {}
        results = []
        for row in SCENARIOS:
            scenario_stage, variant = row[0], row[1]
            profile = row[2] if len(row) > 2 else "default"
            if profile not in binaries:
                binaries[profile] = build(profile)
            done = run(binaries[profile], scenario_stage, variant)
            summary = ""
            for line in done.stdout.splitlines():
                if line.startswith("SIM_RESULT=") and "CHECKS_FAILED" in line:
                    summary = line.strip()
            results.append((scenario_stage, variant, done.returncode, summary))
            print("%-12s %-12s rc=%d  %s" % (scenario_stage, variant,
                                             done.returncode, summary))
        failed = [r for r in results if r[2] != 0]
        print("SIM_VERIFY=%s SCENARIOS=%d FAILED=%d"
              % ("PASS" if not failed else "FAIL", len(results), len(failed)))
        return 1 if failed else 0
    if stage not in ("prepare", "transaction"):
        raise SystemExit("unknown stage: %s (use prepare, transaction, matrix or verify)"
                         % stage)
    variant = sys.argv[2] if len(sys.argv) > 2 else "nominal"
    if variant not in VARIANTS:
        raise SystemExit("unknown variant: %s" % variant)
    prepare_tree()
    binary = build(VARIANT_PROFILE.get(variant, "default"))
    done = run(binary, stage, variant)
    sys.stdout.write(done.stdout)
    if done.stderr.strip():
        sys.stdout.write("\n--- stderr ---\n" + done.stderr)
    return done.returncode


if __name__ == "__main__":
    raise SystemExit(main())
