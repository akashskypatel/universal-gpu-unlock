#!/usr/bin/env python3
"""Render the variant matrix of docs/BUILD_SIGN_DEPLOY.md from docs/image_variants.json.

The catalogue is the source of truth for "every image this repository can
build", `src/Build-Sign-Deploy-UniversalGPU.ps1` executes it, and this renderer
puts it in the user document. `tests/test_image_variants.py` asserts the block
below is exactly this function's output, so the three cannot drift.

    python3 tools/render_image_variants.py          # print the block
    python3 tools/render_image_variants.py --write  # rewrite the document block
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "image_variants.json"
DOCUMENT = ROOT / "docs" / "BUILD_SIGN_DEPLOY.md"
BEGIN = "<!-- IMAGE-VARIANTS:BEGIN (generated by tools/render_image_variants.py from docs/image_variants.json) -->"
END = "<!-- IMAGE-VARIANTS:END -->"


def needs(variant: dict) -> str:
    parts = []
    selection = variant.get("requires_selection")
    if selection == "single":
        parts.append("one BDF")
    elif selection == "sequence":
        parts.append("two or more BDFs")
    elif selection == "any":
        parts.append("one or more BDFs")
    if variant.get("requires_esp_guid"):
        parts.append("reviewed ESP GUID")
    if variant.get("requires_local_boot_profile"):
        parts.append("private `src/local/boot_profile.h`")
    return ", ".join(parts) if parts else "nothing"


def render(manifest: dict) -> str:
    blocks = [BEGIN, ""]
    blocks.append(f"{len(manifest['profiles'])} canonical profiles. "
                  f"{len(manifest['variants'])} compatibility configurations across "
                  f"{len(manifest['families'])} builders.\n\n")
    blocks.append("| Canonical profile | Configurations |\n| --- | ---: |\n")
    for profile in manifest["profiles"]:
        count = sum(v["profile"] == profile["id"] for v in manifest["variants"])
        blocks.append(f"| `{profile['id']}` | {count} |\n")
    blocks.append("\nCompatibility matrix (also available with `-ListLegacy`). Legacy selectors are deprecated; configuration IDs remain stable for receipts and evidence. "
                  "`Safety` is what the image may do to the system, not what it has been shown to do.\n")
    for family in manifest["families"]:
        variants = [v for v in manifest["variants"] if v["family"] == family["id"]]
        blocks.append(f"\n### {family['title']} — `{family['builder']}` (PE subsystem "
                      f"{family['subsystem']}, `{family['status_token']}`)\n\n")
        blocks.append("| Deprecated `-Only` alias / configuration ID | Output | Safety | Needs | What it is |\n")
        blocks.append("| --- | --- | --- | --- | --- |\n")
        for variant in variants:
            blocks.append(f"| `{variant['id']}` | `{variant['binary']}` | "
                          f"`{variant['safety']}` | {needs(variant)} | {variant['note']} |\n")
    blocks.append("\n### Not buildable, and why\n\n")
    for blocked in manifest["not_buildable"]:
        blocks.append(f"* `{blocked['id']}` — {blocked['why']}\n")
    blocks.append("\n")
    blocks.append(END)
    return "".join(blocks)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite the document block")
    args = parser.parse_args(argv)
    block = render(json.loads(MANIFEST.read_text(encoding="utf-8")))
    if args.write:
        text = DOCUMENT.read_text(encoding="utf-8")
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        DOCUMENT.write_text(text[:start] + block + text[end:], encoding="utf-8", newline="\n")
        print(f"wrote {DOCUMENT.relative_to(ROOT)}")
    else:
        print(block, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
