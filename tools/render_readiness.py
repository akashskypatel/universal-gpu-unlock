#!/usr/bin/env python3
"""Render the readiness summary block at the top of the inventory.

`docs/readiness_status.json` is the source of truth: one row per inventory item
(A1..A8, B1..B10, C1..C10, D1..D5, E1..E10) recording whether the item's own
source obligation is met, partly met, or untouched, and pointing at the fix-log
section that says so.

The block is generated so the headline number cannot drift from the per-item
state - and so the number cannot be quietly improved by editing prose. Two rules
keep it honest:

* "met" means a source change exists and a host test, simulator row or CI job
  pins it. It never means the behaviour is proven;
* `hardware_verified` is false for every item, because nothing in this tree has
  executed on a GPU. That is reported as its own number rather than folded into
  the progress claim.

    python3 tools/render_readiness.py           # print
    python3 tools/render_readiness.py --write   # regenerate the block in the doc
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "readiness_status.json"
INVENTORY = ROOT / "docs" / "PRODUCTION_READINESS_INVENTORY.md"
BEGIN = "<!-- READINESS-SUMMARY:BEGIN (generated by tools/render_readiness.py from docs/readiness_status.json) -->"
END = "<!-- READINESS-SUMMARY:END -->"
CLASSES = ("A", "B", "C", "D", "E")


def percent(part: float, whole: int) -> int:
    return int(round(100.0 * part / whole)) if whole else 0


def render(manifest: dict) -> str:
    items = manifest["items"]
    total = len(items)
    counts = {state: sum(1 for i in items if i["source"] == state)
              for state in ("done", "partial", "none")}
    # Half credit for partial: the exit criteria are a list, and half of a list is
    # not a finished item, so this is deliberately not rounded up to "met".
    progress = counts["done"] + 0.5 * counts["partial"]
    verified = sum(1 for i in items if i.get("hardware_verified"))
    p0 = [i for i in items if i["priority"] == "P0"]

    out = [BEGIN, "", "## Readiness at a glance", ""]
    out.append(
        f"{total} tracked items, reviewed {manifest['reviewed']}. Generated from "
        "`docs/readiness_status.json`; `tests/test_readiness_summary.py` fails if this "
        "block and that file disagree, so the headline cannot drift from the per-item "
        "state.")
    out.append("")
    out.append("| Source obligation | Items | Share |")
    out.append("| --- | --- | --- |")
    out.append(
        f"| Met - implemented, and pinned by a host test, simulator row or CI job "
        f"| {counts['done']} | {percent(counts['done'], total)}% |")
    out.append(
        f"| Partial - some exit criteria implemented, the remainder named "
        f"| {counts['partial']} | {percent(counts['partial'], total)}% |")
    out.append(
        f"| Not started | {counts['none']} | {percent(counts['none'], total)}% |")
    out.append("")
    out.append(f"**Source progress: {percent(progress, total)}%** "
               f"({counts['done']} met + half of {counts['partial']} partial = "
               f"{progress:g} of {total}). "
               f"**Verified on hardware: {verified} of {total} "
               f"({percent(verified, total)}%).**")
    out.append("")
    out.append("| Class | Met | Partial | Not started | Total |")
    out.append("| --- | --- | --- | --- | --- |")
    for letter in CLASSES:
        rows = [i for i in items if i["class"] == letter]
        out.append("| {} - {} | {} | {} | {} | {} |".format(
            letter, _class_name(letter),
            sum(1 for i in rows if i["source"] == "done"),
            sum(1 for i in rows if i["source"] == "partial"),
            sum(1 for i in rows if i["source"] == "none"),
            len(rows)))
    out.append("")
    out.append(
        f"Blocking `P0`: {len(p0)} items, "
        f"{sum(1 for i in p0 if i['source'] == 'done')} met, "
        f"{sum(1 for i in p0 if i['source'] == 'partial')} partial, "
        f"{sum(1 for i in p0 if i['source'] == 'none')} not started.")
    out.append("")
    out.append("What the percentage is not: a measure of the product working. A met item "
               "means the code exists and something on the host pins it; the behaviour it "
               "would perform on a GPU is still unproven, which is why the second number "
               "is the one that decides whether this product works. It is 0% because no "
               "run has ever driven a card.")
    out.append("")
    out.append(END)
    return "\n".join(out)


def _class_name(letter: str) -> str:
    return {
        "A": "architecture coupling to the build machine",
        "B": "hardware preconditions",
        "C": "privileged operations never shown safe",
        "D": "release engineering",
        "E": "evidence the product depends on",
    }[letter]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    block = render(json.loads(MANIFEST.read_text(encoding="utf-8")))
    if not args.write:
        print(block)
        return 0
    document = INVENTORY.read_text(encoding="utf-8")
    if BEGIN not in document or END not in document:
        raise SystemExit("the inventory has no readiness summary markers")
    start = document.index(BEGIN)
    stop = document.index(END) + len(END)
    INVENTORY.write_text(document[:start] + block + document[stop:], encoding="utf-8")
    print(f"wrote the readiness summary in {INVENTORY.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
