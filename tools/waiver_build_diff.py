#!/usr/bin/env python3
"""Build the admitted (waiver) image and diff it against the checked one.

Stage S1 of the inventory's ordered plan ends with two requirements that are pure
CI work:

  * "CI builds and diffs the admitted image";
  * D2 — "CI build of the waiver path with a synthetic GUID".

Neither had a mechanism: the workflow built preparation-only images, and the
waiver path was only ever described in a runbook. `GU_ACTIVE_UNVERIFIED_ACTUATION`
is the single switch that turns an image from "refuses to actuate" into "may
attempt the unverified transaction", so *what it changes* should be a reviewed,
pinned fact rather than a claim in a document.

What this tool does, per translation unit, for the same sources:

    checked   = GU_AD104_TRANSACTION + GU_ACTIVE_SINGLE_TARGET + GU_RUNTIME_SELECTION
    admitted  = checked + GU_ACTIVE_UNVERIFIED_ACTUATION

  1. diffs the preprocessor define sets. The expected delta is exactly one macro,
     listed below; anything else means the waiver reaches further than reviewed.
  2. diffs the defined symbols of the compiled object. The expected delta is
     empty: the waiver must not add or remove code in any module.

It prints one line per changed translation unit and a final
`WAIVER_DIFF=PASS|FAIL`. A failure is not "the build is broken" - it is "the
waiver now changes something nobody reviewed", and the fix is to review it and
update the pin here with a reason.

This is a hosted build of the same sources, self-contained: it writes its own
placeholder `local/boot_profile.h` so it runs on a clean checkout before anything
else has generated state. It proves source-level shape, not that MSVC/EDK II
produce the same image - the Windows job compiles the real thing. `docs/UNVERIFIED_ACTUATION_RUNBOOK.md` remains the instruction for
the real build.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The base transaction profile. Deliberately spelled out here instead of imported
# from the simulator: this tool's job is to be an independent witness of what the
# waiver changes, so sharing the runner's flags would couple the two.
BASE = ["-std=c11", "-fshort-wchar", "-O1", "-Wall", "-Wextra",
        "-Wno-unused-parameter"]
BASE_DEFINES = ["-DGU_AD104_TRANSACTION", "-DGU_ENTRY_LATCHED_SS1_FULL",
                "-DGU_ACTIVE_SINGLE_TARGET", "-DGU_RUNTIME_SELECTION"]
WAIVER = ["-DGU_ACTIVE_UNVERIFIED_ACTUATION"]
INCLUDES = ["-I", str(ROOT / "src"), "-I", str(ROOT / "src" / "compat"),
            "-I", str(ROOT / "src" / "vendor"),
            "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include"),
            "-I", str(ROOT / "src" / "vendor" / "edk2" / "Include" / "X64")]

# `src/boot_profile.h` includes `local/boot_profile.h`, which is gitignored: the
# real one is the operator's reviewed ESP GUID. This tool must run on a clean
# checkout, so it writes its own placeholder ahead of everything else. Both sides
# of the diff compile against the same placeholder, so the GUID cancels out and
# cannot influence the deltas being measured.
BOOT_PROFILE = """/* Generated by tools/waiver_build_diff.py. Not a partition GUID. */
#pragma once
#define GU_WINDOWS_PARTITION_INITIALIZER \
  {0x00000000,0x0000,0x4000,{0x80,0x00,0x00,0x00,0x00,0x00,0x00,0x01}}
"""

SOURCES = [
    "app.c", "driver_nvram.c", "boot_io.c", "msi_release.c", "stop_contract.c",
    "launch_source.c",
    "unlock_execution.c",
    "port.c", "compat.c", "checks.c", "gpu_inventory.c", "gpu_discovery.c",
    "gpu_execution_state.c", "gpu_windows_path.c", "profile.c",
    "prom_reference.c", "gpu_selection.c", "gpu_sku_geometry.c", "boot_state.c",
    "asset_install.c", "sha256.c", "runtime.c", "format.c",
    "vendor/unlock_610.c", "vendor/prep_610.c", "vendor/layout_610.c",
    "vendor/vbios_610.c", "vendor/gfw_eval.c",
]

# --- the reviewed difference between the two images -------------------------
#
# One macro, and only one. `GU_ACTUATION_SIMULATED` is already 0 in both builds
# and `GU_PREFLIGHT_ONLY` is already 0 in a transaction build, so the waiver
# changes exactly the admission constant that every gate reads.
EXPECTED_MACRO_DELTAS: dict[str, tuple[str | None, str | None]] = {
    # The flag itself is visible in every translation unit, because it arrives
    # on the command line.
    "GU_ACTIVE_UNVERIFIED_ACTUATION": (None, "1"),
    # And the admission constant it feeds is visible wherever port.h is
    # included, which is where every gate reads it.
    "GU_ACTUATION_ADMITTED": ("0", "1"),
}
# The one delta that must actually occur, or the waiver changed nothing at all.
REQUIRED_MACRO_DELTA = ("GU_ACTUATION_ADMITTED", "0", "1")
# No module gains or loses code. A symbol delta here means the waiver is
# compiling a different program, not flipping a gate inside the same one.
EXPECTED_SYMBOL_DELTA_UNITS: set[str] = set()

DEFINE_RE = re.compile(r"^#define\s+(\w+)(?:\s+(.*))?$")


def compiler() -> str:
    return os.environ.get("CC", "gcc")


def prepare(workdir: Path) -> list[str]:
    """Write the placeholder boot profile and return the include order for it."""
    local = workdir / "local"
    local.mkdir(parents=True, exist_ok=True)
    (local / "boot_profile.h").write_text(BOOT_PROFILE, encoding="utf-8")
    return ["-I", str(workdir)]


def defines_for(source: str, extra: list[str], workdir: Path,
                bootstrap: list[str]) -> dict[str, str]:
    command = [compiler(), *BASE, *BASE_DEFINES, *extra, "-D__KERNEL__",
               *bootstrap, *INCLUDES, "-E", "-dM", str(ROOT / "src" / source)]
    done = subprocess.run(command, capture_output=True, text=True, cwd=workdir)
    if done.returncode != 0:
        raise SystemExit(f"preprocess failed: {source}\n{done.stderr[:2000]}")
    found: dict[str, str] = {}
    for line in done.stdout.splitlines():
        match = DEFINE_RE.match(line.strip())
        if match:
            found[match.group(1)] = (match.group(2) or "").strip()
    return found


def symbols_for(source: str, extra: list[str], workdir: Path,
                bootstrap: list[str] | None = None) -> set[str]:
    obj = workdir / (Path(source).stem + ("_admitted" if extra else "_checked") + ".o")
    if bootstrap is None:
        bootstrap = prepare(workdir)
    command = [compiler(), *BASE, *BASE_DEFINES, *extra, "-D__KERNEL__",
               *bootstrap, *INCLUDES, "-c", str(ROOT / "src" / source), "-o", str(obj)]
    done = subprocess.run(command, capture_output=True, text=True, cwd=workdir)
    if done.returncode != 0:
        raise SystemExit(f"compile failed: {source}\n{done.stderr[:2000]}")
    listed = subprocess.run(["nm", "--defined-only", str(obj)],
                            capture_output=True, text=True)
    if listed.returncode != 0:
        raise SystemExit(f"nm failed: {source}\n{listed.stderr[:2000]}")
    names = set()
    for line in listed.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 3:
            names.add(parts[2])
    return names


def compare(workdir: Path, sources: list[str]) -> tuple[list[str], int, set, int]:
    problems: list[str] = []
    macro_delta_total = 0
    seen: set = set()
    admitted_units = 0
    bootstrap = prepare(workdir)
    for source in sources:
        checked_macros = defines_for(source, [], workdir, bootstrap)
        admitted_macros = defines_for(source, WAIVER, workdir, bootstrap)
        delta = {}
        for name in set(checked_macros) | set(admitted_macros):
            before = checked_macros.get(name)
            after = admitted_macros.get(name)
            if before != after:
                delta[name] = (before, after)
        if delta:
            macro_delta_total += len(delta)
            for name, (before, after) in sorted(delta.items()):
                if EXPECTED_MACRO_DELTAS.get(name) != (before, after):
                    problems.append(
                        f"{source}: unreviewed macro delta {name}: "
                        f"{before!r} -> {after!r}")
                seen.add((name, before, after))
            if ("GU_ACTUATION_ADMITTED", "0", "1") in {
                    (n, b, a) for n, (b, a) in delta.items()}:
                admitted_units += 1
        checked_symbols = symbols_for(source, [], workdir, bootstrap)
        admitted_symbols = symbols_for(source, WAIVER, workdir, bootstrap)
        symbol_delta = checked_symbols ^ admitted_symbols
        if symbol_delta:
            print(f"WAIVER_DIFF_UNIT={source} SYMBOL_DELTA="
                  f"{','.join(sorted(symbol_delta))}")
            if source not in EXPECTED_SYMBOL_DELTA_UNITS:
                problems.append(
                    f"{source}: the waiver adds or removes code: "
                    f"{', '.join(sorted(symbol_delta))}")
    return problems, macro_delta_total, seen, admitted_units


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    if not shutil.which(compiler()):
        print(f"WAIVER_DIFF=SKIP NO_COMPILER={compiler()}")
        return 0
    with tempfile.TemporaryDirectory() as directory:
        problems, macro_total, seen, admitted_units = compare(Path(directory), SOURCES)
    if REQUIRED_MACRO_DELTA not in seen:
        problems.append(
            "the waiver does not reach GU_ACTUATION_ADMITTED in any translation "
            "unit: it is not admitting anything, so this build proves nothing")
    for problem in problems:
        print(f"WAIVER_DIFF_PROBLEM={problem}")
    if problems:
        print(f"WAIVER_DIFF=FAIL SOURCES={len(SOURCES)} PROBLEMS={len(problems)}")
        return 1
    if not args.quiet:
        for name, (before, after) in sorted(EXPECTED_MACRO_DELTAS.items()):
            print(f"WAIVER_DIFF_ALLOWED={name}:{before}->{after}")
    print(f"WAIVER_DIFF=PASS SOURCES={len(SOURCES)} "
          f"MACRO_DELTAS={macro_total} ADMITTED_UNITS={admitted_units} "
          f"SYMBOL_DELTAS=0 ADMITTED_BY=GU_ACTIVE_UNVERIFIED_ACTUATION")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
